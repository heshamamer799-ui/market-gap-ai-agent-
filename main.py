# 1. استيراد المكتبات الأساسية لإدارة الوكلاء والاتصال بالنموذج الذكي
from crewai import Agent, Task, Crew, Process
from langchain_google_genai import  ChatGoogleGenerativeAI
import os

# 2. إعداد مفتاح API الخاص بـ Gemini وتشغيل النموذج
# (يمكنك الحصول عليه مجاناً من Google AI Studio)
os.environ["GEMINI_API_KEY"] = "YOUR_GEMINI_API_KEY"
llm = ChatGoogleGenerativeAI(model="gemini-1.5-flash", temperature=0.7)

# 3. تعريف "الوكيل الباحث" (Market Research Agent)
# مهمته تصفح المتاجر، وقراءة التقييمات، والبحث عن المنتجات والأدوات المطلوبة
market_researcher = Agent(
    role='محلل أسواق ناشئة وخبير منصات رقمية',
    goal='البحث في منصات مثل أمازون ومتاجر التطبيقات لاستخراج المنتجات والأدوات ذات الطلب العالي والتي تعاني من تقييمات سلبيّة أو نقص في الميزات',
    backstory='أنت خبير محترف في تحليل البيانات التجارية، تستطيع قراءة مراجعات المستخدمين واكتشاف المشاكل التي يواجهها التجار والمشترون في كتب التلوين، الدفاتر، والتطبيقات الحاسبة للعمولات.',
    verbose=True,
    llm=llm
)

# 4. تعريف "وكيل التسويق بالعمولة وتطوير الأعمال" (Affiliate & Business Strategy Agent)
# مهمته أخذ الثغرات وتحويلها إلى فرصة بيزنس، وربطها بعروض تسويق بالعمولة مربحة
business_strategist = Agent(
    role='مستشار تطوير أعمال ومسوق بالعمولة',
    goal='تحويل الثغرات المكتشفة إلى أفكار منتجات رقمية (أدوات، كتب، تطبيقات) واقتراح أفضل برامج التسويق بالعمولة للاستفادة منها وحساب هوامش الربح للتاجر',
    backstory='أنت مستشار أعمال عبقري، تعرف كيف تبني بيزنس رقمي بميزانية صفرية، وتجيد اختيار منصات البيع والربط بين الأدوات وحسابات العمولات لتجني الأرباح للتجار.',
    verbose=True,
    llm=llm
)

# 5. تحديد المهام (Tasks) التي سيقوم بها الوكلاء بالتتابع
task1 = Task(
    description='ابحث عن ثغرات في مشاريع كتب التلوين للأطفال والتطبيقات الرقمية الصغيرة (مثل حاسبات العمولات للتجارة الإلكترونية). ركز على الشكاوى الشائعة للمستخدمين هذا الشهر.',
    expected_output='تقرير مفصل يوضح 3 ثغرات رئيسية في السوق (الطلب مقابل ضعف الجودة الشديد).',
    agent=market_researcher
)

task2 = Task(
    description='بناءً على التقرير المستخرج، ضع خطة عمل لإنشاء منتج رقمي يحل هذه المشكلة، واقترح برنامج تسويق بالعمولة (Affiliate) يمكن دمجه لتحقيق دخل سلبي سريع، مع توضيح كيفية تسويقه بميزانية صفرية.',
    expected_output='خطة عمل تنفيذية تشمل: فكرة المنتج، منصة البيع المقترحة، والروابط أو الأدوات المقترحة للتسويق بالعمولة لزيادة الربحية.',
    agent=business_strategist
)

# 6. تشغيل النظام (Crew) لبدء العمل الجماعي بين الوكلاء
digital_biz_crew = Crew(
    agents=[market_researcher, business_strategist],
    tasks=[task1, task2],
    process=Process.sequential # تنفيذ المهام بالتتالي
)

# إطلاق الوكيل لاستخراج النتائج
result = digital_biz_crew.kickoff()
print(result)
